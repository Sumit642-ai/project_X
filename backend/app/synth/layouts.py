"""File layouts as the (fictional) source systems emit them.

These are the source side. backend/app/datalayer_mock/ingest/contracts/ declares what
ingestion expects; the ingest tests check that the two agree.
"""

from dataclasses import dataclass
from typing import Literal


@dataclass(frozen=True)
class Layout:
    feed: str
    stream: str
    load_key: str  # key into catalog.LOAD_DATES
    fmt: Literal["csv", "json"]
    columns: tuple[str, ...]

    def file_name(self, load_date: str) -> str:
        return f"{self.feed}/{self.stream}_{load_date}.{self.fmt}"


