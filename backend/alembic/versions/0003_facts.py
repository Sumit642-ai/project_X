POSTGRES_TRIGGER = """
CREATE FUNCTION facts_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'facts are append-only: cannot delete';
    END IF;
    IF OLD.superseded_by IS NOT NULL OR NEW.superseded_by IS NULL
       OR (to_jsonb(NEW) - 'superseded_by') IS DISTINCT FROM (to_jsonb(OLD) - 'superseded_by')
    THEN
        RAISE EXCEPTION 'facts are append-only: only superseded_by may be set, once';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER facts_append_only BEFORE UPDATE OR DELETE ON facts
    FOR EACH ROW EXECUTE FUNCTION facts_append_only();
"""


